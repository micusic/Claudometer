import AppKit

/// Palette mirroring the Windows build, chosen by the effective appearance at draw time.
struct Theme {
    let bg, card, border, divider, track, hover: NSColor
    let text, muted, faint, accent, onAccent: NSColor
    let okText, warnText, dangerText: NSColor
    let okFill, warnFill, dangerFill: NSColor
    let grid, axis: NSColor

    static func current(_ dark: Bool) -> Theme { dark ? darkTheme : lightTheme }

    static func c(_ r: Int, _ g: Int, _ b: Int) -> NSColor {
        NSColor(srgbRed: CGFloat(r)/255, green: CGFloat(g)/255, blue: CGFloat(b)/255, alpha: 1)
    }

    static let lightTheme = Theme(
        bg: c(255,255,255), card: c(0xF3,0xF5,0xF8), border: c(0xDD,0xE1,0xE6), divider: c(0xEE,0xF0,0xF3),
        track: c(0xEA,0xED,0xF1), hover: c(0xEE,0xF1,0xF5),
        text: c(0x1A,0x1E,0x24), muted: c(0x5C,0x66,0x72), faint: c(0x93,0x9C,0xA8),
        accent: c(0x3B,0x6F,0xE0), onAccent: c(255,255,255),
        okText: c(0x12,0x76,0x3B), warnText: c(0xAD,0x63,0x08), dangerText: c(0xC0,0x36,0x2B),
        okFill: c(0x27,0xAE,0x60), warnFill: c(0xF2,0xA0,0x28), dangerFill: c(0xE2,0x4A,0x3B),
        grid: c(0xED,0xF0,0xF3), axis: c(0x9A,0xA2,0xAD))

    static let darkTheme = Theme(
        bg: c(0x1E,0x21,0x26), card: c(0x2C,0x30,0x37), border: c(0x40,0x45,0x4E), divider: c(0x2E,0x32,0x39),
        track: c(0x2C,0x30,0x37), hover: c(0x34,0x39,0x42),
        text: c(0xE6,0xE8,0xEB), muted: c(0x9A,0xA0,0xA8), faint: c(0x6C,0x74,0x7E),
        accent: c(0x5B,0x8A,0xF0), onAccent: c(255,255,255),
        okText: c(0x4E,0xC7,0x82), warnText: c(0xE7,0xA9,0x3A), dangerText: c(0xE8,0x6E,0x62),
        okFill: c(0x2E,0xA9,0x5F), warnFill: c(0xE0,0x9A,0x24), dangerFill: c(0xD8,0x4C,0x4C),
        grid: c(0x38,0x3C,0x44), axis: c(0x78,0x7E,0x88))

    func levelText(_ pct: Double) -> NSColor { pct >= 90 ? dangerText : pct >= 70 ? warnText : okText }
    func levelFill(_ pct: Double) -> NSColor { pct >= 90 ? dangerFill : pct >= 70 ? warnFill : okFill }
}
